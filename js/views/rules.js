// Свойства фигур и краткие правила (из таблицы «Пять ликов одной Луны» и правил боя).
import { cache } from '../api.js?v=202610161008';
import { h, card, GIFT_RU } from '../ui.js?v=202610161008';

const PHASE_ORDER = ['Условие', 'Сила', 'Риск', 'Ущерб', 'Перемещение'];

export default async function rulesView(root) {
  const q = h('input', { type: 'search', placeholder: 'Найти свойство', 'aria-label': 'Поиск свойства', style: 'flex: 1 1 14rem' });
  const list = h('div', { class: 'stack' });
  const draw = () => {
    const s = q.value.trim().toLowerCase();
    list.replaceChildren(...PHASE_ORDER.map((ph) => {
      const props = cache.properties.filter((p) => p.phase === ph && (!s || (p.name + ' ' + p.description).toLowerCase().includes(s)));
      if (!props.length) return '';
      return h('div', { class: 'stack' }, h('div', { class: 'phase-head' }, ph === 'Перемещение' ? 'Перемещение (вне боя)' : 'Фаза: ' + ph),
        props.map((p) => h('div', {}, h('b', {}, p.name),
          h('span', { class: 'muted small' }, ' · ' + (p.cost ? p.cost + ' Р.' : p.cost_note ? p.cost_note + ' Р.' : 'бесплатно')),
          h('div', { class: 'prop-desc' }, p.description))));
    }));
  };
  q.addEventListener('input', draw);
  draw();

  root.append(
    h('h1', { class: 'page-title' }, 'Свойства и правила'),
    h('div', { class: 'grid' },
      card('Бой',
        h('ul', { class: 'small', style: 'margin:0; padding-left: 1.2em; display: grid; gap: 4px' },
          h('li', {}, 'Фазы: Условия → Сила → Риск → Ущерб. Каждая фигура действует не больше одного раза за бой, по решению стратега.'),
          h('li', {}, 'Внутри фазы — по номиналу (король быстрее всех, пешка медленнее), затем по Лояльности (выше — раньше), затем атакующий.'),
          h('li', {}, 'Риск: каждый бросает d10 и прибавляет к Силе; больше — победа, поровну — ничья. «10» — автопобеда; обе автопобеды — ничья.'),
          h('li', {}, 'Ущерб: проигравший сам выбирает, какую фигуру повредить (повреждённую повторно нельзя). Повреждённая фигура сохраняет Силу и свойства.'),
          h('li', {}, 'Отряд уничтожен, если после фазы Ущерба все его фигуры повреждены. В конце игры в уничтоженном отряде погибает одна фигура (выбор владельца или жребий).'))),
      card('Отряды',
        h('ul', { class: 'small', style: 'margin:0; padding-left: 1.2em; display: grid; gap: 4px' },
          h('li', {}, 'В отряде от 1 до 3 фигур; Сила, Лояльность и Влияние отряда — суммы по фигурам. У каждого отряда своё название, уникальное в игре.'),
          h('li', {}, 'Отрядов — 2 + 1 за каждые 3 точки Влияния (бонус вносит ведущий). Во всех отрядах стратега не больше 8 пешек, 2 коней, 2 офицеров, 2 ладей, 1 ферзя, 1 короля.'),
          h('li', {}, 'Напарники — один стратег на двоих: фигуры вперемешку без передачи, ограничения общие, Ресурсы складываются, доп. отряды — по большему из двух.'),
          h('li', {}, 'Трофеев у отряда не больше 3. Победитель может забрать у побеждённого один трофей, если есть место. Выкинуть трофей можно в любой момент, кроме боя (от нападения до итога).'),
          h('li', {}, 'Ход отряда: движение (Перемещение или «Стоит на месте»), затем одно действие — Нападение, Обмен (со своим отрядом рядом), Активация фишки или «Стоит на месте». После действия ход отряда закончен; действие можно заявить и без движения.'),
          h('li', {}, 'Обмен заканчивает ход только отряду, который его начал; второй отряд ходит дальше.'))),
      card('Дары лун',
        h('ul', { class: 'small', style: 'margin:0; padding-left: 1.2em; display: grid; gap: 4px' },
          h('li', {}, h('b', {}, GIFT_RU.alaya + '. '), 'Поражение в бою — +1 Ярость, победа — Ярость сгорает. 1 Ярость: +1 к перемещению на ход, или +5 к Силе в бою (раз за бой), или активировать фишку издалека (в пределах Влияния).'),
          h('li', {}, h('b', {}, GIFT_RU.belaya + '. '), 'Три разных номинала подряд в отряде (например, пешка-конь-офицер): +2 к Силе в боях и +1 действие в событиях. Одинаковые номиналы — штраф к Лояльности при попытке переманить фигуру.'),
          h('li', {}, h('b', {}, GIFT_RU.gorkaya + '. '), 'На карте 5 Эхо Расколотого мира — зон с особыми правилами, неизвестными заранее (Святилище: Подкуп и Плен не работают; Болото: движения стоят +1 Ресурс). Эхо занимает часть карты: его правила действуют на отряд, который прошёл через него или остановился в нём.'),
          h('li', {}, h('b', {}, GIFT_RU.chernaya + '. '), 'Движение 4 гекса (Мобильность и Замри — тоже 4). Ход делится на такты: за такт стратег действует одним отрядом, и когда ход этого отряда закончен, ход переходит дальше. Стратег с 3+ отрядами не может быть в первой тройке по инициативе — сайт сам ставит его после неё.')))),
    h('section', { class: 'card' }, h('header', {}, h('h2', {}, 'Свойства фигур'), q), list));
}
